/*
 * webgui_html.h — Embedded frontend page.
 *
 * Served via ws.h's HTTP fallback when a non-WebSocket request hits the
 * server root. Connects back to the same host as a WebSocket client.
 *
 * Protocol (JSON over WebSocket, UTF-8 text frames):
 *
 *   Server -> Client:
 *     { "type": "render", "title": "...", "icon": "...", "tree": <node> }
 *     { "type": "set_text",     "id": "...", "value": "..." }
 *     { "type": "set_value",    "id": "...", "value": "..." }
 *     { "type": "set_disabled", "id": "...", "value": true | false }
 *     { "type": "set_visible",  "id": "...", "value": true | false }
 *     { "type": "set_attr",     "id": "...", "key": "...", "value": "..." }
 *     { "type": "append",       "parent": "...", "node": <node> }
 *     { "type": "insert",       "parent": "...", "index": N, "node": <node> }
 *     { "type": "remove",       "parent": "...", "child": "..." }
 *     { "type": "meta",         "title": "...", "icon": "..." }
 *
 *   <node>:
 *     { "id": "...",
 *       "kind": "container|text|heading|button|input|checkbox|select|image|separator|form",
 *       "level": 1,             (heading only)
 *       "text": "..." | null,
 *       "value": "..." | null,
 *       "disabled": false,
 *       "visible": true,
 *       "options": [...]        (select only)
 *       "attrs": { "key": "val", ... },
 *       "children": [<node>, ...] }
 *
 *   Client -> Server:
 *     { "type": "event", "id": "...", "event": "click" }
 *     { "type": "event", "id": "...", "event": "input",  "value": "..." }
 *     { "type": "event", "id": "...", "event": "change", "value": "..." }
 *     { "type": "event", "id": "form_id", "event": "submit",
 *       "form_data": { "child_id": "value", ... } }
 */

